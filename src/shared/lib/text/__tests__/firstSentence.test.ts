import { firstSentence } from '../firstSentence';

describe('firstSentence', () => {
  test('первое предложение', () => {
    expect(firstSentence('У вас тёмное зрение. Оно работает на 60 фт.')).toBe('У вас тёмное зрение.');
  });

  test('сокращения не обрывают предложение', () => {
    expect(firstSentence('Укус: 1к4 + мод. ТЕЛ колющего урона. Дальше.')).toBe('Укус: 1к4 + мод. ТЕЛ колющего урона.');
    expect(firstSentence('Черта на выбор (см. главу 5). Ещё.')).toBe('Черта на выбор (см. главу 5).');
  });

  test('без точки — весь текст, лишние пробелы убраны', () => {
    expect(firstSentence('  Сопротивление   урону ядом ')).toBe('Сопротивление урону ядом');
  });
});
